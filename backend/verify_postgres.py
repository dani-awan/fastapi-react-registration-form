"""Run against a real local PostgreSQL database; remove only this run's test row."""
import os
from uuid import uuid4

from dotenv import load_dotenv
load_dotenv()
if not os.getenv('DATABASE_URL', '').startswith('postgresql+psycopg://'):
    raise SystemExit('Set a PostgreSQL DATABASE_URL in backend/.env first.')

from fastapi.testclient import TestClient
from sqlalchemy import delete, select, text
from app.main import app, engine, SessionLocal, User, password_hasher


def main():
    email = f'verify-{uuid4().hex}@example.com'
    payload = {'name': 'Database Verification', 'email': email,
               'phone': '03001234567', 'password': 'VerifyPass123'}
    with TestClient(app) as client:
        try:
            with engine.connect() as connection:
                version = connection.scalar(text('SELECT version()'))
                assert 'PostgreSQL' in version
            print('PASS: real PostgreSQL connection')
            response = client.post('/api/register', json=payload)
            assert response.status_code == 201, response.text
            saved_id = response.json()['id']
            assert 'password' not in response.json()
            assert 'password_hash' not in response.json()
            with SessionLocal() as db:
                user = db.scalar(select(User).where(User.email == email))
                assert user is not None and user.id == saved_id
                assert user.name == payload['name'] and user.phone == payload['phone']
                assert user.password_hash != payload['password']
                assert password_hasher.verify(payload['password'], user.password_hash)
            print('PASS: API insert persisted in PostgreSQL')
            print('PASS: Argon2 password hash and response privacy')
            duplicate = client.post('/api/register', json=payload)
            assert duplicate.status_code == 409, duplicate.text
            print('PASS: duplicate email rejected')
            invalid = client.post('/api/register', json={**payload, 'phone': '123'})
            assert invalid.status_code == 422, invalid.text
            with SessionLocal() as db:
                rows = db.scalars(select(User).where(User.email == email)).all()
                assert len(rows) == 1
            print('PASS: invalid input rejected without inserting a row')
        finally:
            # Delete only the unique email generated by this test.
            with SessionLocal() as db:
                db.execute(delete(User).where(User.email == email))
                db.commit()
            print('Test record removed; existing records preserved.')
    print('SUCCESS: all PostgreSQL integration checks passed.')


if __name__ == '__main__':
    main()
